import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneModule from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const standalone = standaloneModule.default ?? standaloneModule;
const desktop = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(desktop, "../..");
const check = process.argv.includes("--check");
const arguments_ = process.argv.slice(2);
const selection = arguments_.filter(arg => arg.startsWith("--domain="));
if (selection.length > 1 || arguments_.some(arg => arg !== "--check" && !/^--domain=(project|execution|source|translation|resource|review|release|ai|arena)$/.test(arg))) throw new Error("Usage: generate-contracts.mjs [--check] [--domain=project|execution|source|translation|resource|review|release|ai|arena]");
const selectedDomain = selection[0]?.slice("--domain=".length);
const temporary = await mkdtemp(join(tmpdir(), "tsumugi-ipc-"));
try {
  const destination = join(temporary, "ipc.schema.json");
  const cargo = spawnSync("cargo", ["run", "-p", "tsumugi-desktop", "--features", "wire-schema", "--locked", "--", "--export-ipc-schema", destination], { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
  if (cargo.status !== 0) throw new Error(cargo.error?.message ?? cargo.stderr ?? "Schema export failed");
  const domains = JSON.parse(await readFile(destination, "utf8"));
  if (selectedDomain && !Object.hasOwn(domains, selectedDomain)) throw new Error("Requested schema domain is missing");
  const banner = "Generated by pnpm generate:contracts from Rust/Serde. Do not edit.";
  const output = new Map();
  for (const [domain, schemas] of Object.entries(domains)) {
    if (selectedDomain && domain !== selectedDomain) continue;
    const prefix = domain === "project" ? "" : `${domain}.`;
    const ajv = new Ajv({ strict: true, validateFormats: false, code: { source: true, esm: true, lines: true } });
    const exports = {}, declarations = [], enums = [];
    for (const [group, schema] of Object.entries(schemas)) {
      const title = group === "requests" ? "Requests" : "Responses";
      const id = `urn:tsumugi:ipc:${domain === "project" ? "" : `${domain}:`}${group}`;
      schema.$id = id;
      schema.$comment = banner;
      schema.title = title;
      ajv.addSchema(schema);
      if (group === "responses") {
        for (const [name, definition] of Object.entries(schema.definitions ?? {})) {
          if (Array.isArray(definition.enum)) enums.push(`export const ${name}Values = ${JSON.stringify(definition.enum)} as const;`);
        }
      }
      output.set(`${prefix}${group}.d.ts`, await compile(schema, title, { bannerComment: `/* ${banner} */`, additionalProperties: false, unknownAny: true }));
      for (const key of Object.keys(schema.properties)) {
        const name = `validate${title.slice(0, -1)}${key[0].toUpperCase()}${key.slice(1)}`;
        const validatorId = `${id}:${key}`;
        ajv.addSchema({ $id: validatorId, $ref: `${id}#/properties/${key}` });
        exports[name] = validatorId;
        declarations.push(`export declare function ${name}(value: unknown): value is ${title}[${JSON.stringify(key)}];`);
      }
    }
    const code = standalone(ajv, exports);
    // This schema slice requires no Ajv runtime helpers or dynamic compilation.
    // A later schema that adds one must explicitly bundle it for the browser.
    if (/\brequire\s*\(/.test(code)) throw new Error("Standalone validator requires an unbundled runtime helper");
    output.set(`${prefix}validators.js`, `// ${banner}\n${code.trimEnd()}\n`);
    output.set(`${prefix}validators.d.ts`, `// ${banner}\nimport type { Requests } from "./${prefix}requests";\nimport type { Responses } from "./${prefix}responses";\n${declarations.join("\n")}\n`);
    output.set(`${prefix}enums.ts`, `// ${banner}\n${enums.join("\n")}\n`);
    output.set(`${prefix}ipc.schema.json`, JSON.stringify(schemas, null, 2) + "\n");
  }
  const generated = join(desktop, "src", "generated");
  if (!check) await mkdir(generated, { recursive: true });
  for (const [name, content] of output) {
    const path = join(generated, name);
    if (check) {
      if ((await readFile(path, "utf8")).replace(/\r\n/g, "\n") !== content) throw new Error(`Generated contract differs: ${name}`);
    } else await writeFile(path, content);
  }
  process.stdout.write(check ? "Generated IPC contracts are current.\n" : "Generated IPC types, schemas and validators.\n");
} finally {
  const resolved = await realpath(temporary);
  const inside = relative(await realpath(tmpdir()), resolved);
  if (!inside || inside.startsWith(`..${sep}`) || inside === ".." || inside.includes(sep) || !inside.startsWith("tsumugi-ipc-")) throw new Error("Unexpected temporary schema directory");
  await rm(resolved, { recursive: true, force: true });
}
